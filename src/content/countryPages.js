// One page per Gulf country, for people searching there. Each page carries its
// own currency, prices, cities and health authorities, and states plainly what
// the system does not integrate with: MARKETING_CLAIMS.md rules out implying
// compliance or local customers we can't evidence. Prices come from pricing.js.

import { COUNTRY_PAGE_PATHS } from '../lib/seo.js'
import { countryByCode, currencyFor } from '../lib/countries.js'
import { formatPrice, getPricing, pricePerMonth } from '../lib/pricing.js'

const TRIAL = '14 يوماً تجربة مجانية بدون بطاقة بنكية.'

function countryPage({ code, name, keyword, title, cities, intro, localSection, integrations, extraFaqs }) {
  const { plans, currency } = getPricing(code)
  const { label, name: currencyName, inWord } = currencyFor(currency)
  const { dial } = countryByCode(code)
  const [one, three, six] = plans
  const money = (n) => `${formatPrice(n)} ${label}`

  return {
    slug: COUNTRY_PAGE_PATHS[code].slice(1),
    group: 'countries',
    groupLabel: 'بسهولة في الخليج',
    country: code,
    keyword,
    title,
    description: `${keyword}: حجز مواعيد أونلاين، تذكير واتساب من رقمك، وملف لكل مريض. يبدأ من ${money(one.price)} شهرياً، مع ${TRIAL}`,
    h1: keyword,
    intro,
    sections: [
      {
        h2: `حجز مواعيد مرضاك في ${cities}`,
        body: `يحجز المريض موعده بنفسه من رابط باسم عيادتك في أي وقت، ويرى المواعيد المتاحة فقط. أرقام المرضى تُسجَّل بكود ${name} (+${dial})، فتفتح محادثة واتساب مع المريض مباشرة.`,
        bullets: [
          'صفحة حجز أونلاين برابط خاص بعيادتك',
          'تذكير واتساب من رقمك بضغطة زر',
          'ملف لكل مريض بالزيارات والمدفوعات',
          'أيام وساعات عمل تحددها لكل فرع',
          'قائمة انتظار',
          'تقارير الحضور والغياب',
        ],
      },
      localSection,
      {
        h2: `الأسعار في ${name} ${inWord}`,
        body: `الاشتراك مبلغ ثابت ${inWord} وبدون عمولة على الحجوزات، وكل الباقات تفتح النظام بالكامل. أسعار خدماتك تظهر لمرضاك بعملة ${currencyName}.`,
        bullets: [
          `باقة شهر واحد: ${money(one.price)} شهرياً`,
          `باقة 3 شهور: ${money(three.price)} (ما يعادل ${money(pricePerMonth(three))} شهرياً)`,
          `باقة 6 شهور: ${money(six.price)} (ما يعادل ${money(pricePerMonth(six))} شهرياً)`,
        ],
      },
      {
        h2: 'ما يجب أن تعرفه قبل الاشتراك',
        body: `بسهولة نظام لتنظيم الحجوزات ومتابعة المرضى، وليس مربوطاً بأنظمة الجهات الحكومية أو التأمين في ${name}. ${integrations} كما أننا لا نضمن حالياً تخزين البيانات داخل ${name}، فإن كان نشاطك ملزماً بذلك فراجع الجهة المنظمة قبل استخدام الملفات الطبية.`,
      },
      {
        h2: 'الاشتراك والدعم',
        body: `جرّب النظام ${TRIAL} وعند الاشتراك تتواصل معنا على واتساب لنتفق على طريقة الدفع، فلا يوجد دفع إلكتروني داخل النظام. الدعم الفني بالعربية على واتساب من فريق بسهولة في مصر.`,
      },
    ],
    faqs: [
      {
        q: `كم سعر برنامج العيادات في ${name}؟`,
        a: `يبدأ من ${money(one.price)} شهرياً، وينزل إلى ما يعادل ${money(pricePerMonth(six))} شهرياً في باقة الستة شهور، بكل المميزات وحجوزات غير محدودة.`,
      },
      {
        q: `هل يدعم النظام أرقام ${name} وعملتها؟`,
        a: `نعم. تختار ${name} عند إنشاء الحساب، فتظهر أسعار خدماتك بعملة ${currencyName}، وتُسجَّل أرقام المرضى بكود +${dial}.`,
      },
      {
        q: 'كيف أدفع الاشتراك؟',
        a: 'تتواصل معنا على واتساب ونتفق على طريقة الدفع. التجربة نفسها لا تحتاج أي بيانات دفع.',
      },
      ...extraFaqs,
    ],
    related: ['pricing', 'solutions/clinics', 'features/whatsapp-reminders'],
  }
}

